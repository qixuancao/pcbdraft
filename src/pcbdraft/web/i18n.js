export function assertDictionaryParity(dictionaries = DICTIONARIES) {
  const locales = Object.keys(dictionaries);
  const baseline = Object.keys(dictionaries[locales[0]] || {}).sort().join("\u0000");
  for (const locale of locales.slice(1)) {
    if (Object.keys(dictionaries[locale] || {}).sort().join("\u0000") !== baseline) {
      throw new Error(`i18n keys differ for ${locale}`);
    }
  }
  return true;
}

export function normalizeLocale(value) {
  return value === "zh-CN" || String(value || "").toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function createI18n(initialLocale) {
  assertDictionaryParity();
  let locale = normalizeLocale(initialLocale);
  function translate(key, values = {}) {
    const template = DICTIONARIES[locale][key] || DICTIONARIES.en[key] || key;
    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => String(values[name] ?? ""));
  }
  return {
    get locale() {
      return locale;
    },
    setLocale(next) {
      locale = normalizeLocale(next);
      document.documentElement.lang = locale;
      document.title = translate("document.title");
      return locale;
    },
    t: translate,
    apply(root = document) {
      for (const node of root.querySelectorAll("[data-i18n]")) {
        node.textContent = translate(node.dataset.i18n);
      }
      for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
        node.setAttribute("placeholder", translate(node.dataset.i18nPlaceholder));
      }
      for (const node of root.querySelectorAll("[data-i18n-title]")) {
        node.setAttribute("title", translate(node.dataset.i18nTitle));
      }
      for (const node of root.querySelectorAll("[data-i18n-aria]")) {
        node.setAttribute("aria-label", translate(node.dataset.i18nAria));
      }
      for (const node of root.querySelectorAll("[data-i18n-alt]")) {
        node.setAttribute("alt", translate(node.dataset.i18nAlt));
      }
    },
  };
}

